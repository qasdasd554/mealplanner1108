"""Generate immutable display labels from reviewed translations, never DB writes.

Exact seed IDs and original source text protect user content and stale overlays.
No new runtime HTTP request or extra recipe-list payload is needed.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path
import re
from uuid import UUID, uuid5

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'frontend/lib/l10n/system_content_data.dart'
INDEX_OUTPUT = ROOT / 'backend/app/data/system_content_index.json'
NAMESPACE = UUID('a1b2c3d4-e5f6-7890-abcd-ef1234567890')


def build():
    tree = ast.parse((ROOT / 'backend/app/db/seed.py').read_text(encoding='utf-8'))
    assignments = {node.targets[0].id: node.value for node in tree.body
                   if isinstance(node, ast.Assign) and len(node.targets) == 1
                   and isinstance(node.targets[0], ast.Name)}
    assignments.update({node.target.id: node.value for node in tree.body
                        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)})
    recipe_nodes = assignments['RECIPES_DATA'].elts + assignments['AIRFRYER_RECIPES'].elts
    text_keys = {'name', 'description', 'instructions', 'suggested_seasonings'}
    recipes = [{ast.literal_eval(key): ast.literal_eval(value)
                for key, value in zip(node.keys, node.values)
                if ast.literal_eval(key) in text_keys} for node in recipe_nodes]
    # seed.py normalises descriptions AFTER the literal recipe declarations.
    # The display registry must fingerprint the actual persisted text, not the
    # pre-normalisation AST; otherwise valid system translations disappear.
    # Runtime-seed parity is independently checked in the backend regression.
    for recipe in recipes:
        if recipe.get('description'):
            recipe['description'] = recipe['description'].replace(' — ', '. ')
    recipe_ingredient_names = {ast.literal_eval(ingredient.elts[0])
        for node in recipe_nodes for key, value in zip(node.keys, node.values)
        if ast.literal_eval(key) == 'ingredients' for ingredient in value.elts}
    # The catalogue includes foods not yet used by the bundled recipes. They
    # need the same display/search identity; otherwise valid system foods are
    # mistaken for arbitrary Polish branded SKUs during UK OFF review.
    # Read literal seed data, never execute seed_database or connect to a DB.
    product_nodes = (assignments['PRODUCTS_DATA'].elts
                     + assignments['ADDITIONAL_RECIPE_PRODUCTS_100'].elts)
    ingredient_names = sorted(ast.literal_eval(node.elts[0]) for node in product_nodes)
    assert len(ingredient_names) == len(set(ingredient_names)), 'Duplicate catalogue identity'
    assert recipe_ingredient_names <= set(ingredient_names), 'Recipe food missing from catalogue'
    english = json.loads((ROOT / 'backend/app/data/system_recipes_en_GB.json').read_text(encoding='utf-8'))
    labels = json.loads((ROOT / 'backend/app/data/system_ingredients_en_GB.json').read_text(encoding='utf-8'))
    assert len(recipes) == 137
    assert set(english) == {recipe['name'] for recipe in recipes}
    assert set(labels) == set(ingredient_names)
    registry = {}
    for recipe in recipes:
        source = {key: recipe.get(key, [] if key in {'instructions', 'suggested_seasonings'} else None)
                  for key in ['name', 'description', 'instructions', 'suggested_seasonings']}
        translated = english[recipe['name']]
        assert set(source) == set(translated)
        assert len(source['instructions']) == len(translated['instructions'])
        assert len(source['suggested_seasonings']) == len(translated['suggested_seasonings'])
        for key in source:
            # Quantities, temperatures and durations must survive translation.
            numbers = lambda value: [number.replace(',', '.') for number in re.findall(
                r'\d+(?:[.,]\d+)?', json.dumps(value, ensure_ascii=False))]
            assert numbers(source[key]) == numbers(translated[key]), (recipe['name'], key)
        registry[str(uuid5(NAMESPACE, 'recipe:' + recipe['name']))] = dict(source=source, en_GB=translated)
    ingredients = {str(uuid5(NAMESPACE, 'product:' + name)): dict(source=name, en_GB=labels[name])
                   for name in ingredient_names}

    def dart(value):
        return json.dumps(value, ensure_ascii=False, indent=2).replace('$', r'\$')

    dart_source = ('// GENERATED by scripts/build_system_content_labels.py. Do not edit.\n'
            '// Canonical source text and exact seed IDs are intentional guards.\n'
            'const systemRecipeText = <String, Map<String, dynamic>>' + dart(registry) + ';\n\n'
            'const systemIngredientText = <String, Map<String, String>>' + dart(ingredients) + ';\n')
    index = {'recipes': {key: {'source': row['source']['name'],
                              'description': row['source']['description'],
                              'en_GB': row['en_GB']['name'],
                              'detail_sha256': hashlib.sha256(json.dumps(row['source'],
                                  sort_keys=True, ensure_ascii=False, separators=(',', ':')).encode()).hexdigest()}
                         for key, row in registry.items()}, 'ingredients': ingredients}
    return dart_source, index


def parsed_maps(source):
    """Read generated JSON-compatible Dart maps after dart format's commas."""
    def without_trailing_commas(text):
        quoted, escaped, result = False, False, []
        for offset, char in enumerate(text):
            if quoted:
                result.append(char)
                if escaped:
                    escaped = False
                elif char == '\\':
                    escaped = True
                elif char == '"':
                    quoted = False
            elif char == '"':
                quoted = True
                result.append(char)
            elif char != ',' or not text[offset + 1:].lstrip().startswith(('}', ']')):
                result.append(char)
        return ''.join(result).replace(r'\$', '$')

    maps = []
    for name in ['systemRecipeText', 'systemIngredientText']:
        part = source.split('const ' + name + ' = ', 1)[1]
        start = part.index('{')
        end = part.index('\n};', start) if '\n};' in part else part.index('};', start)
        maps.append(json.loads(without_trailing_commas(part[start:end + (2 if part[end] == '\n' else 1)])))
    return maps


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data, index = build()
    if args.check:
        assert OUTPUT.is_file()
        assert parsed_maps(OUTPUT.read_text(encoding='utf-8')) == parsed_maps(data)
        assert json.loads(INDEX_OUTPUT.read_text(encoding='utf-8')) == index
        print(f'Source/translation contract: {len(index["recipes"])} recipes, '
              f'{len(index["ingredients"])} ingredients, quantities unchanged.')
    else:
        OUTPUT.write_text(data, encoding='utf-8', newline='\n')
        INDEX_OUTPUT.write_text(json.dumps(index, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
        print(OUTPUT)


if __name__ == '__main__':
    main()
